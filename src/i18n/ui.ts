const strings: Record<Locale, Record<UiKey, string>> = { en, de };

/** `t('filter.count', { count: 3, total: 6 })` → "3 of 6 projects shown" */
export function useTranslations(locale: Locale) {
  return (key: UiKey, vars: Record<string, string | number> = {}) =>
    strings[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

